# CSE 3521 - Group Alpha
# M2: TF-IDF using Lecture 6 formulas

import numpy as np
from sklearn.feature_extraction.text import CountVectorizer
from scipy.sparse import diags

# STEP 1: Build vocabulary and count words (BOW)
vectorizer = CountVectorizer(max_features=5000)

X_train_bow = vectorizer.fit_transform(
    train_df["Clean_Text"]
)
X_test_bow = vectorizer.transform(
    test_df["Clean_Text"]
)

# STEP 2: Calculate Term Frequency (TF)
# TF = word count / total words in review
train_lengths = np.asarray(
    X_train_bow.sum(axis=1)
).ravel()

test_lengths = np.asarray(
    X_test_bow.sum(axis=1)
).ravel()

train_lengths = np.maximum(train_lengths, 1)
test_lengths = np.maximum(test_lengths, 1)

TF_train = diags(1 / train_lengths) @ X_train_bow
TF_test = diags(1 / test_lengths) @ X_test_bow

# STEP 3: Calculate Inverse Document Frequency
# IDF = log(N / df)
N = X_train_bow.shape[0]

df_counts = np.asarray(
    (X_train_bow > 0).sum(axis=0)
).ravel()

idf = np.log(N / df_counts)

# STEP 4: TF-IDF = TF * IDF
X_train_tfidf = TF_train.multiply(idf).tocsr()
X_test_tfidf = TF_test.multiply(idf).tocsr()

# STEP 5: Display results
feature_names = vectorizer.get_feature_names_out()

print("===== LECTURE 6 TF-IDF RESULTS =====")
print("Vocabulary size:", len(feature_names))
print("Training matrix:", X_train_tfidf.shape)
print("Testing matrix:", X_test_tfidf.shape)

# Top 10 words by average TF-IDF
avg_scores = np.asarray(
    X_train_tfidf.mean(axis=0)
).ravel()

top_indices = np.argsort(avg_scores)[-10:][::-1]

print("\nTop 10 words by average TF-IDF:")
for i in top_indices:
    print(feature_names[i], round(avg_scores[i], 4))

# CSE 3521 - Group Alpha
# M2: Top Positive and Negative TF-IDF Features

import numpy as np
import pandas as pd

# Separate training reviews by sentiment
positive_mask = train_df["Sentiment"].to_numpy() == 1
negative_mask = train_df["Sentiment"].to_numpy() == 0

# Average TF-IDF scores for each class
positive_avg = np.asarray(
    X_train_tfidf[positive_mask].mean(axis=0)
).ravel()

negative_avg = np.asarray(
    X_train_tfidf[negative_mask].mean(axis=0)
).ravel()

# Difference in average TF-IDF scores
difference = positive_avg - negative_avg

# Top 10 positive and negative features
top_positive = np.argsort(difference)[-10:][::-1]
top_negative = np.argsort(difference)[:10]

print("===== TOP 10 POSITIVE FEATURES =====")
