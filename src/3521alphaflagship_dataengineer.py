# Load the uploaded dataset
df = pd.read_csv("group_sample_seed42.csv")

print("\nOriginal reviews:", len(df))

# STEP 2: Remove missing values
df = df.dropna(subset=["Text", "Score"]).copy()

# STEP 3: Remove duplicate review texts
df = df.drop_duplicates(subset=["Text"]).copy()

# STEP 4: Clean review text
def clean_text(text):
    text = str(text).lower()
    text = re.sub(r"<[^>]+>", " ", text)
    text = re.sub(r"[^a-z0-9\s']", " ", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()

df["Clean_Text"] = df["Text"].apply(clean_text)

# Remove empty reviews
df = df[df["Clean_Text"] != ""].copy()

# STEP 5: Create sentiment labels
# 0 = Negative (1-3 stars)
# 1 = Positive (4-5 stars)
df["Sentiment"] = (df["Score"] >= 4).astype(int)

# STEP 6: Split into training and testing data
train_df, test_df = train_test_split(
    df,
    test_size=0.20,
    random_state=42,
    stratify=df["Sentiment"]
)

# STEP 7: Save the datasets
train_df.to_csv("alpha_train.csv", index=False)
